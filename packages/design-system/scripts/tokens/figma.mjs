// Design-tool profile for Figma (TDD tokens FG1-FG6): the emitted Tier-2 color and
// dimension tokens as Design Tokens Format Module 2025.10 files that Figma's
// native variable import reads.
//
//   tokens/figma/<theme>.<mode>.color.tokens.json   one file per mode (FG2)
//   tokens/figma/<theme>.dimension.tokens.json      one file per theme (FG4)
//
// The repository stays the only source (ADR-UIP-TKN-004): these files are
// derived from the same normalized records as the CSS and JSON outputs and are
// never read back.

import Color from "colorjs.io";
import { parseTokenName } from "./grammar.mjs";
import { substitute } from "./validate.mjs";

export const FIGMA_DIR = "tokens/figma";
const HEADER = "Generated by @scnx/system scripts/tokens/emit.mjs from the token source. Do not edit.";
const EXTENSION = "com.scnehaux.ui";
const ROOT_FONT_SIZE = 16;

const round = (n) => Math.round(n * 1e4) / 1e4;

/**
 * FG3: Figma imports colors in sRGB or HSL only. A color outside sRGB is clipped:
 * that is the srgb-clip display path the contrast gate measures, and the palette
 * gate keeps it within 0.02 ΔEok of the CSS gamut-mapped rendering (TDD tokens PG6),
 * so every imported pair is one the gates checked.
 */
export function srgbValue(css) {
  const color = new Color(css).to("srgb").toGamut({ method: "clip" });
  const components = color.coords.map((c) => round(Math.min(1, Math.max(0, c ?? 0))));
  const value = { colorSpace: "srgb", components, hex: new Color("srgb", components).toString({ format: "hex", collapse: false }) };
  const alpha = Number(color.alpha ?? 1);
  if (alpha < 1) value.alpha = round(alpha);
  return value;
}

/** FG4: a dimension as a unitless pixel number (Figma variables are unitless floats). */
export function pixelValue(css) {
  const match = /^(-?\d*\.?\d+)(px|rem)?$/.exec(css.trim());
  if (!match) throw new Error(`no pixel value for "${css}"`);
  const value = Number(match[1]);
  return match[2] === "rem" ? round(value * ROOT_FONT_SIZE) : value;
}

function place(root, path, leaf) {
  const keys = path.split(".");
  let node = root;
  for (const key of keys.slice(0, -1)) {
    if (node[key] && "$value" in node[key]) throw new Error(`${path}: "${key}" is both a token and a group`);
    node = node[key] ??= {};
  }
  node[keys.at(-1)] = leaf;
}

function token(type, value, cssName) {
  // FG5: the CSS name rides along so a plugin can set the variable's WEB code syntax.
  return { $type: type, $value: value, $extensions: { [EXTENSION]: { cssName, codeSyntax: { WEB: `var(${cssName})` } } } };
}

/** The resolved value of every record of one theme/mode whose domain is `domain`. */
function resolvedIn(values, aliases, domain) {
  const out = [];
  for (const [cssName, css] of values) {
    const parsed = parseTokenName(cssName, aliases);
    if (!parsed.valid || parsed.tier !== 2 || !parsed.path.startsWith(`${domain}.`)) continue;
    const resolved = substitute(css, (name) => values.get(name));
    if (resolved.missing?.length || resolved.cycles?.length) throw new Error(`${cssName}: unresolved reference`);
    out.push({ cssName, path: parsed.path, value: resolved.value });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

/** Every Figma profile file of one theme: [{ file, content }]. */
export function figmaFiles(themeId, modes, config) {
  const aliases = config.aliases ?? {};
  const files = [];
  const doc = (description) => ({ $description: `${HEADER} ${description}` });
  const stringify = (value) => `${JSON.stringify(value, null, 2)}\n`;

  for (const [mode, values] of Object.entries(modes)) {
    const root = doc(`Theme "${themeId}", mode "${mode}": import into one mode of a Color collection.`);
    for (const { cssName, path, value } of resolvedIn(values, aliases, "color")) place(root, path, token("color", srgbValue(value), cssName));
    files.push({ file: `${FIGMA_DIR}/${themeId}.${mode}.color.tokens.json`, content: stringify(root) });
  }

  // FG4: dimensions do not vary by mode; a theme whose modes disagree stops emission.
  const [first, ...rest] = Object.entries(modes);
  const dimensions = resolvedIn(first[1], aliases, "dimension");
  for (const [mode, values] of rest) {
    const other = new Map(resolvedIn(values, aliases, "dimension").map((d) => [d.path, d.value]));
    for (const d of dimensions) if (other.get(d.path) !== d.value) throw new Error(`${themeId}/${mode} ${d.cssName}: dimensions differ between modes`);
  }
  const root = doc(`Theme "${themeId}": import into a single-mode Dimension collection. Values are pixels.`);
  for (const { cssName, path, value } of dimensions) place(root, path, token("number", pixelValue(value), cssName));
  files.push({ file: `${FIGMA_DIR}/${themeId}.dimension.tokens.json`, content: stringify(root) });
  return files;
}
